/** مصنع خطوة: ماذا / لماذا / كيف تتأكد / إن لم ينجح */
export const s = (
  what: string,
  why: string,
  verify: string,
  ifFailed?: string
): ActionStep => ({ what, why, verify, ...(ifFailed ? { ifFailed } : {}) });

